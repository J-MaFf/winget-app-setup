    Context 'Set-WindowsTerminalDefaults orchestration' {
        BeforeEach {
            # Deterministic same-user, non-SYSTEM state by default; the skip tests override.
            Mock Test-IsSystemAccount { $false }
            Mock Get-ProcessUserName { 'CONTOSO\jdoe' }
            Mock Get-InteractiveSessionUserName { 'CONTOSO\jdoe' }
            Mock Write-WarningMessage { }
            # Windows Terminal is present by default (issue #271); the "not installed" gate is
            # covered by its own tests below.
            Mock Test-WindowsTerminalInstalled { $true }
        }

        It 'Should perform no writes in WhatIf mode' {
            Mock Get-WindowsTerminalSettingsPaths { return @('C:\temp\settings.json') }
            Mock Set-WindowsTerminalDefaultProfile { return $true }
            Mock Set-WindowsTerminalAsDefaultTerminalApplication { return $true }
            Mock Write-Info { }

            Set-WindowsTerminalDefaults -WhatIf

            Should -Invoke Set-WindowsTerminalDefaultProfile -Times 0
            Should -Invoke Set-WindowsTerminalAsDefaultTerminalApplication -Times 0
            Should -Invoke Write-Info -Times 2
        }

        It 'Should configure both settings file and registry in normal mode' {
            Mock Get-WindowsTerminalSettingsPaths { return @('C:\temp\settings.json') }
            Mock Set-WindowsTerminalDefaultProfile { return $true }
            Mock Set-WindowsTerminalAsDefaultTerminalApplication { return $true }

            Set-WindowsTerminalDefaults

            Should -Invoke Set-WindowsTerminalDefaultProfile -Times 1
            Should -Invoke Set-WindowsTerminalAsDefaultTerminalApplication -Times 1
        }

        It 'Should configure all discovered settings files in normal mode' {
            Mock Get-WindowsTerminalSettingsPaths { return @('C:\temp\stable-settings.json', 'C:\temp\preview-settings.json') }
            Mock Set-WindowsTerminalDefaultProfile { return $true }
            Mock Set-WindowsTerminalAsDefaultTerminalApplication { return $true }

            Set-WindowsTerminalDefaults

            Should -Invoke Set-WindowsTerminalDefaultProfile -Times 2
            Should -Invoke Set-WindowsTerminalAsDefaultTerminalApplication -Times 1
        }

        It 'Should configure the logged-on user without a skip line when process and session users match' {
            Mock Get-WindowsTerminalSettingsPaths { return @('C:\temp\settings.json') }
            Mock Set-WindowsTerminalDefaultProfile { return $true }
            Mock Set-WindowsTerminalAsDefaultTerminalApplication { return $true }
            Mock Write-Info { }

            Set-WindowsTerminalDefaults

            Should -Invoke Write-Info -Times 0 -ParameterFilter { $Message -match 'Skipping Windows Terminal defaults' }
            Should -Invoke Set-WindowsTerminalDefaultProfile -Times 1
        }

        It 'Skips the whole step with one line under cross-user elevation, writing nothing for the admin account' {
            Mock Get-WindowsTerminalSettingsPaths { return @('C:\temp\settings.json') }
            Mock Set-WindowsTerminalDefaultProfile { return $true }
            Mock Set-WindowsTerminalAsDefaultTerminalApplication { return $true }
            Mock Write-Info { }
            Mock Get-ProcessUserName { 'CONTOSO\admin-tech' }
            Mock Get-InteractiveSessionUserName { 'CONTOSO\jdoe' }

            Set-WindowsTerminalDefaults

